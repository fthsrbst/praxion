/// One generated ingredient: the tag it came from (if any) and the concrete
/// items it accepts. A plain item has `tag: None` and one entry in `items`.
#[derive(Clone, Debug)]
struct IngredientDef {
    tag: Option<String>,
    items: Vec<String>,
}

#[derive(Clone, Debug)]
enum ShapeDef {
    Shaped {
        width: u8,
        height: u8,
        grid: Vec<Option<IngredientDef>>,
    },
    Shapeless {
        ingredients: Vec<IngredientDef>,
    },
}

#[derive(Clone, Debug)]
struct RecipeDef {
    output: String,
    output_count: u32,
    needs_table: bool,
    shape: ShapeDef,
}

fn load_recipes(
    jar: &mut Jar,
    item_tags: &BTreeMap<String, BTreeSet<String>>,
) -> Result<Vec<RecipeDef>, String> {
    let prefix = "data/minecraft/recipe/";
    let names: Vec<String> = jar
        .file_names()
        .filter_map(Result::ok)
        .filter(|name| name.starts_with(prefix) && name.ends_with(".json"))
        .map(|name| name.into_owned())
        .collect();

    let mut recipes = Vec::new();
    for name in names {
        let bytes = read_entry(jar, &name)?;
        let json: Value =
            serde_json::from_slice(&bytes).map_err(|e| format!("{name}: invalid JSON: {e}"))?;
        let Some(kind) = json.get("type").and_then(Value::as_str) else {
            return Err(format!("{name}: missing `type`"));
        };
        if !matches!(
            kind,
            "minecraft:crafting_shaped" | "minecraft:crafting_shapeless"
        ) {
            // Special, smelting, stonecutting and smithing recipes are not
            // crafting recipes the `craft` primitive can run.
            continue;
        }
        let Some((output, output_count)) = result_of(&json, &name)? else {
            continue;
        };
        match kind {
            "minecraft:crafting_shaped" => {
                let pattern = json
                    .get("pattern")
                    .and_then(Value::as_array)
                    .ok_or_else(|| format!("{name}: missing `pattern`"))?
                    .iter()
                    .map(|line| {
                        line.as_str()
                            .map(str::to_string)
                            .ok_or_else(|| format!("{name}: a pattern line is not a string"))
                    })
                    .collect::<Result<Vec<_>, _>>()?;
                if pattern.is_empty() {
                    return Err(format!("{name}: empty pattern"));
                }
                let width = pattern.iter().map(|line| line.chars().count()).max().unwrap_or(0);
                let height = pattern.len();
                if width == 0 || width > 3 || height > 3 {
                    // Vanilla has no larger crafting grid; a larger pattern
                    // would be a data error.
                    return Err(format!("{name}: pattern is {width}x{height}"));
                }
                let key = json
                    .get("key")
                    .and_then(Value::as_object)
                    .ok_or_else(|| format!("{name}: missing `key`"))?;
                let mut ingredients: BTreeMap<char, IngredientDef> = BTreeMap::new();
                for (symbol, value) in key {
                    let symbol = symbol
                        .chars()
                        .next()
                        .ok_or_else(|| format!("{name}: an empty key symbol"))?;
                    ingredients.insert(symbol, ingredient(value, item_tags, &name)?);
                }
                let mut grid = Vec::with_capacity(width * height);
                for line in &pattern {
                    let mut chars = line.chars();
                    for _ in 0..width {
                        match chars.next() {
                            None | Some(' ') => grid.push(None),
                            Some(symbol) => {
                                let ingredient = ingredients.get(&symbol).cloned().ok_or_else(|| {
                                    format!("{name}: pattern symbol `{symbol}` is not in `key`")
                                })?;
                                grid.push(Some(ingredient));
                            }
                        }
                    }
                }
                recipes.push(RecipeDef {
                    output,
                    output_count,
                    needs_table: width > 2 || height > 2,
                    shape: ShapeDef::Shaped {
                        width: width as u8,
                        height: height as u8,
                        grid,
                    },
                });
            }
            "minecraft:crafting_shapeless" => {
                let values = json
                    .get("ingredients")
                    .and_then(Value::as_array)
                    .ok_or_else(|| format!("{name}: missing `ingredients`"))?;
                let mut ingredients = Vec::with_capacity(values.len());
                for value in values {
                    ingredients.push(ingredient(value, item_tags, &name)?);
                }
                recipes.push(RecipeDef {
                    output,
                    output_count,
                    needs_table: ingredients.len() > 4,
                    shape: ShapeDef::Shapeless { ingredients },
                });
            }
            _ => unreachable!("only shaped and shapeless recipes reach this match"),
        }
    }

    // Deterministic order: by output, then the recipe with the largest yield
    // first (vanilla has several recipes for a few items, e.g. sticks from
    // planks and from bamboo).
    recipes.sort_by(|a, b| {
        a.output
            .cmp(&b.output)
            .then_with(|| b.output_count.cmp(&a.output_count))
            .then_with(|| format!("{:?}", a.shape).cmp(&format!("{:?}", b.shape)))
    });
    recipes.dedup_by(|a, b| {
        a.output == b.output
            && a.output_count == b.output_count
            && format!("{:?}", a.shape) == format!("{:?}", b.shape)
    });
    Ok(recipes)
}

fn result_of(json: &Value, name: &str) -> Result<Option<(String, u32)>, String> {
    let Some(result) = json.get("result") else {
        return Ok(None);
    };
    match result {
        Value::String(id) => Ok(Some((normalize(id), 1))),
        Value::Object(object) => {
            let id = object
                .get("id")
                .or_else(|| object.get("item"))
                .and_then(Value::as_str)
                .ok_or_else(|| format!("{name}: result has no `id`"))?;
            let count = object.get("count").and_then(Value::as_u64).unwrap_or(1);
            let count = u32::try_from(count).map_err(|_| format!("{name}: result count too large"))?;
            Ok(Some((normalize(id), count)))
        }
        other => Err(format!("{name}: unsupported result {other}")),
    }
}

fn ingredient(
    value: &Value,
    item_tags: &BTreeMap<String, BTreeSet<String>>,
    name: &str,
) -> Result<IngredientDef, String> {
    let mut tag = None;
    let mut items = BTreeSet::new();
    match value {
        Value::String(text) => add_ingredient_entry(text, &mut tag, &mut items, item_tags),
        Value::Array(values) => {
            for value in values {
                let text = value
                    .as_str()
                    .ok_or_else(|| format!("{name}: an ingredient alternative is not a string"))?;
                add_ingredient_entry(text, &mut tag, &mut items, item_tags);
            }
        }
        Value::Object(object) => {
            if let Some(text) = object.get("item").and_then(Value::as_str) {
                add_ingredient_entry(text, &mut tag, &mut items, item_tags);
            } else if let Some(text) = object.get("tag").and_then(Value::as_str) {
                add_ingredient_entry(&format!("#{text}"), &mut tag, &mut items, item_tags);
            } else {
                return Err(format!("{name}: an ingredient object has no `item` or `tag`"));
            }
        }
        other => return Err(format!("{name}: unsupported ingredient {other}")),
    }
    if items.is_empty() {
        return Err(format!("{name}: an ingredient resolves to no item"));
    }
    Ok(IngredientDef {
        tag,
        items: items.into_iter().collect(),
    })
}

fn add_ingredient_entry(
    text: &str,
    tag: &mut Option<String>,
    items: &mut BTreeSet<String>,
    item_tags: &BTreeMap<String, BTreeSet<String>>,
) {
    if let Some(name) = text.strip_prefix('#') {
        let name = normalize(name);
        *tag = Some(name.clone());
        if let Some(values) = item_tags.get(&name) {
            items.extend(values.iter().cloned());
        }
    } else {
        items.insert(normalize(text));
    }
}

