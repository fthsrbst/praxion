//! Build-time reader for the pinned 26.3 server jar.
//!
//! It reads the loot tables for the blocks and mobs the core skills and the
//! fake world use, and writes `loot.rs` into `OUT_DIR`. The jar is the single
//! source; `src/recipes.rs` holds the hand-transcribed recipe table from the
//! same data pack.
//!
//! The server jar is a zip holding a versioned zip; the `zip` crate reads both.
//! This file only knows the loot-table shapes those tables use: pools with
//! `rolls: 1`, `item`, `alternatives`, nested `loot_table` references,
//! `survives_explosion`, silk-touch/shears conditions, `match_tool`, and the
//! `set_count` modifier. Anything else fails the build and names the table.

use std::fs;
use std::io::{Cursor, Read, Seek};
use std::path::{Path, PathBuf};

use serde_json::Value;
use zip::ZipArchive;

const BLOCKS: &[&str] = &[
    "stone",
    "cobblestone",
    "oak_log",
    "grass_block",
    "dirt",
    "crafting_table",
    "iron_ore",
    "coal_ore",
];
const ENTITIES: &[&str] = &["cow", "sheep", "chicken"];

/// The versioned server jar, held in memory and read on demand by entry name.
type Jar = ZipArchive<Cursor<Vec<u8>>>;

fn main() {
    let root = repo_root();
    let jar = jar_path(&root);
    println!("cargo:rerun-if-changed={}", jar.display());
    if !jar.is_file() {
        panic!("gamedata: {} not found; run \"python setup.py\" first", jar.display());
    }

    let file =
        fs::File::open(&jar).unwrap_or_else(|e| panic!("gamedata: {}: {e}", jar.display()));
    let mut outer =
        ZipArchive::new(file).unwrap_or_else(|e| panic!("gamedata: {}: {e}", jar.display()));
    let inner_name = outer
        .file_names()
        .filter_map(Result::ok)
        .find(|name| name.starts_with("META-INF/versions/") && name.ends_with(".jar"))
        .map(|name| name.into_owned())
        .unwrap_or_else(|| panic!("gamedata: {} has no versioned server jar", jar.display()));
    let inner_bytes = read_entry(&mut outer, &inner_name)
        .unwrap_or_else(|e| panic!("gamedata: {}: {e}", jar.display()));
    let mut inner = open_jar(inner_bytes).unwrap_or_else(|e| panic!("gamedata: {inner_name}: {e}"));

    let mut out = String::from("// Generated by build.rs from the 26.3 server jar. Do not edit.\n\n");
    out.push_str("pub const BLOCKS: &[BlockDrops] = &[\n");
    for block in BLOCKS {
        let path = format!("data/minecraft/loot_table/blocks/{block}.json");
        let drops =
            parse_table(&mut inner, &path, 0).unwrap_or_else(|e| panic!("gamedata: {path}: {e}"));
        write_table(&mut out, "BlockDrops", "block", block, &drops);
    }
    out.push_str("];\n\npub const ENTITIES: &[EntityDrops] = &[\n");
    for entity in ENTITIES {
        let path = format!("data/minecraft/loot_table/entities/{entity}.json");
        let drops =
            parse_table(&mut inner, &path, 0).unwrap_or_else(|e| panic!("gamedata: {path}: {e}"));
        write_table(&mut out, "EntityDrops", "entity", entity, &drops);
    }
    out.push_str("];\n");

    let dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(dir.join("loot.rs"), out).expect("gamedata: write loot.rs");
}

/// The repository root, three levels above the crate directory
/// (`<root>/body/crates/gamedata`).
fn repo_root() -> PathBuf {
    let manifest =
        PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    manifest.ancestors().nth(3).unwrap_or(&manifest).to_path_buf()
}

/// The server jar: `server_jar` from `local/paths.toml` when `setup.py` has run,
/// else the jar `setup.py` downloads. A relative value is relative to the
/// repository root, the same rule the harness uses.
fn jar_path(root: &Path) -> PathBuf {
    // Joined piecewise so a Windows error message shows one separator style.
    let default = root
        .join("third_party")
        .join("minecraft")
        .join("server-26.3.jar");

    let paths = root.join("local/paths.toml");
    let Ok(text) = fs::read_to_string(&paths) else {
        return default;
    };
    println!("cargo:rerun-if-changed={}", paths.display());
    let value = toml::from_str::<toml::Value>(&text)
        .unwrap_or_else(|e| panic!("gamedata: {}: {e}", paths.display()));
    let Some(configured) = value
        .get("server_jar")
        .and_then(|jar| jar.as_str())
        .filter(|jar| !jar.trim().is_empty())
    else {
        return default;
    };
    let configured = PathBuf::from(configured);
    if configured.is_absolute() {
        configured
    } else {
        root.join(configured)
    }
}

/// A versioned jar opened from its bytes.
fn open_jar(bytes: Vec<u8>) -> Result<Jar, String> {
    ZipArchive::new(Cursor::new(bytes)).map_err(|e| e.to_string())
}

/// The uncompressed bytes of one entry of `archive`.
fn read_entry<R: Read + Seek>(archive: &mut ZipArchive<R>, name: &str) -> Result<Vec<u8>, String> {
    let mut entry = archive.by_name(name).map_err(|e| format!("entry `{name}`: {e}"))?;
    let mut bytes = Vec::new();
    entry.read_to_end(&mut bytes).map_err(|e| format!("read `{name}`: {e}"))?;
    Ok(bytes)
}

#[derive(Debug)]
struct DropDef {
    item: String,
    min: u32,
    max: u32,
    tool: Option<String>,
}

#[derive(Debug)]
enum Condition {
    Skip,
    Accept(Option<String>),
}

fn parse_table(jar: &mut Jar, path: &str, depth: usize) -> Result<Vec<DropDef>, String> {
    if depth > 8 {
        return Err("loot-table nesting is deeper than 8".into());
    }
    let bytes = read_entry(jar, path)?;
    let json: Value =
        serde_json::from_slice(&bytes).map_err(|e| format!("invalid JSON: {e}"))?;
    let pools = json
        .get("pools")
        .and_then(Value::as_array)
        .ok_or_else(|| "missing `pools`".to_string())?;
    let mut drops = Vec::new();
    for (index, pool) in pools.iter().enumerate() {
        check_rolls(pool, path, index)?;
        if let Some(condition) = pool.get("condition").or_else(|| pool.get("conditions")) {
            if matches!(condition_of(condition, path, false)?, Condition::Skip) {
                continue;
            }
        }
        let entries = pool
            .get("entries")
            .and_then(Value::as_array)
            .ok_or_else(|| format!("pool {index} has no `entries`"))?;
        for entry in entries {
            drops.extend(parse_entry(jar, entry, path, depth, false)?);
        }
    }
    Ok(drops)
}

fn check_rolls(pool: &Value, path: &str, index: usize) -> Result<(), String> {
    match pool.get("rolls") {
        None => Ok(()),
        Some(Value::Number(number)) if number.as_u64() == Some(1) => Ok(()),
        Some(other) => Err(format!(
            "unsupported `rolls` {other} in pool {index} of {path}"
        )),
    }
}

fn parse_entry(
    jar: &mut Jar,
    entry: &Value,
    path: &str,
    depth: usize,
    lenient: bool,
) -> Result<Vec<DropDef>, String> {
    let object = entry
        .as_object()
        .ok_or_else(|| format!("an entry in {path} is not an object"))?;
    let mut tool = None;
    if let Some(condition) = object.get("condition").or_else(|| object.get("conditions")) {
        match condition_of(condition, path, lenient)? {
            Condition::Skip => return Ok(Vec::new()),
            Condition::Accept(found) => tool = found,
        }
    }
    let kind = object
        .get("type")
        .and_then(Value::as_str)
        .ok_or_else(|| format!("an entry in {path} has no `type`"))?;
    match kind {
        "minecraft:item" => {
            let name = object
                .get("name")
                .and_then(Value::as_str)
                .ok_or_else(|| format!("an item entry in {path} has no `name`"))?;
            let (min, max) = counts(object, path)?;
            Ok(vec![DropDef {
                item: normalize(name),
                min,
                max,
                tool,
            }])
        }
        "minecraft:alternatives" => {
            let children = object
                .get("children")
                .and_then(Value::as_array)
                .ok_or_else(|| format!("an alternatives entry in {path} has no `children`"))?;
            for child in children {
                let allowed = match child.get("condition").or_else(|| child.get("conditions")) {
                    Some(condition) => {
                        !matches!(condition_of(condition, path, true)?, Condition::Skip)
                    }
                    None => true,
                };
                if allowed {
                    return parse_entry(jar, child, path, depth, true);
                }
            }
            Ok(Vec::new())
        }
        "minecraft:loot_table" => {
            let value = object
                .get("value")
                .and_then(Value::as_str)
                .ok_or_else(|| format!("a loot_table entry in {path} has no `value`"))?;
            parse_table(jar, &table_path(value), depth + 1)
        }
        other => Err(format!("unsupported entry type `{other}` in {path}")),
    }
}

fn counts(object: &serde_json::Map<String, Value>, path: &str) -> Result<(u32, u32), String> {
    let mut min = 1;
    let mut max = 1;
    let Some(modifiers) = object
        .get("modifier")
        .or_else(|| object.get("modifiers"))
    else {
        return Ok((min, max));
    };
    let list: Vec<&Value> = match modifiers {
        Value::Array(values) => values.iter().collect(),
        other => vec![other],
    };
    for modifier in list {
        let kind = modifier
            .get("type")
            .and_then(Value::as_str)
            .ok_or_else(|| format!("a modifier in {path} has no `type`"))?;
        match kind {
            "minecraft:set_count" => {
                let count = modifier
                    .get("count")
                    .ok_or_else(|| format!("set_count in {path} has no `count`"))?;
                (min, max) = parse_count(count, path)?;
            }
            // Normal mining, no fire, no looting, no fortune and no explosion:
            // these modifiers do not change the base drop.
            "minecraft:furnace_smelt"
            | "minecraft:enchanted_count_increase"
            | "minecraft:apply_bonus"
            | "minecraft:explosion_decay" => {}
            other => return Err(format!("unsupported modifier `{other}` in {path}")),
        }
    }
    Ok((min, max))
}

fn parse_count(value: &Value, path: &str) -> Result<(u32, u32), String> {
    if let Some(count) = value.as_u64() {
        let count = u32::try_from(count).map_err(|_| format!("count {count} is too large"))?;
        return Ok((count, count));
    }
    let object = value
        .as_object()
        .ok_or_else(|| format!("unsupported count {value} in {path}"))?;
    if object.get("type").and_then(Value::as_str) != Some("minecraft:uniform") {
        return Err(format!("unsupported count {value} in {path}"));
    }
    let min = object
        .get("min")
        .and_then(Value::as_u64)
        .ok_or_else(|| format!("uniform count in {path} has no `min`"))?;
    let max = object
        .get("max")
        .and_then(Value::as_u64)
        .ok_or_else(|| format!("uniform count in {path} has no `max`"))?;
    Ok((
        u32::try_from(min).map_err(|_| format!("min {min} is too large"))?,
        u32::try_from(max).map_err(|_| format!("max {max} is too large"))?,
    ))
}

fn condition_of(condition: &Value, path: &str, lenient: bool) -> Result<Condition, String> {
    match condition {
        Value::Array(terms) => {
            let mut tool = None;
            for term in terms {
                match condition_of(term, path, lenient)? {
                    Condition::Skip => return Ok(Condition::Skip),
                    Condition::Accept(found) => tool = tool.or(found),
                }
            }
            Ok(Condition::Accept(tool))
        }
        Value::String(name) => match name.as_str() {
            "minecraft:tool/can_silk_touch" | "minecraft:tool/can_shear" => Ok(Condition::Skip),
            "minecraft:survives_explosion" => Ok(Condition::Accept(None)),
            _other if lenient => Ok(Condition::Accept(None)),
            other => Err(format!("unsupported condition `{other}` in {path}")),
        },
        Value::Object(object) => {
            let kind = object
                .get("type")
                .and_then(Value::as_str)
                .ok_or_else(|| format!("a condition in {path} has no `type`"))?;
            match kind {
                "minecraft:survives_explosion" => Ok(Condition::Accept(None)),
                "minecraft:match_tool" => {
                    let tool = object
                        .get("predicate")
                        .and_then(tool_from_predicate)
                        .map(str::to_string);
                    Ok(Condition::Accept(tool))
                }
                "minecraft:any_of" => {
                    let terms = object
                        .get("terms")
                        .and_then(Value::as_array)
                        .ok_or_else(|| format!("any_of in {path} has no `terms`"))?;
                    let mut tool = None;
                    for term in terms {
                        if let Condition::Accept(found) = condition_of(term, path, lenient)? {
                            tool = tool.or(found);
                        }
                    }
                    Ok(Condition::Accept(tool))
                }
                "minecraft:all_of" => {
                    let terms = object
                        .get("terms")
                        .and_then(Value::as_array)
                        .ok_or_else(|| format!("all_of in {path} has no `terms`"))?;
                    let mut tool = None;
                    for term in terms {
                        match condition_of(term, path, lenient)? {
                            Condition::Skip => return Ok(Condition::Skip),
                            Condition::Accept(found) => tool = tool.or(found),
                        }
                    }
                    Ok(Condition::Accept(tool))
                }
                "minecraft:inverted" => {
                    let term = object
                        .get("term")
                        .ok_or_else(|| format!("inverted in {path} has no `term`"))?;
                    match condition_of(term, path, lenient)? {
                        Condition::Skip => Ok(Condition::Accept(None)),
                        Condition::Accept(_) => Ok(Condition::Skip),
                    }
                }
                _other if lenient => Ok(Condition::Accept(None)),
                other => Err(format!("unsupported condition `{other}` in {path}")),
            }
        }
        _other if lenient => Ok(Condition::Accept(None)),
        other => Err(format!("unsupported condition {other} in {path}")),
    }
}

fn tool_from_predicate(predicate: &Value) -> Option<&str> {
    let items = predicate.get("items")?;
    let list: Vec<&str> = match items {
        Value::String(item) => vec![item.as_str()],
        Value::Array(items) => items.iter().filter_map(Value::as_str).collect(),
        _ => return None,
    };
    for tool in ["pickaxe", "axe", "shovel", "hoe", "shears"] {
        if list.iter().any(|item| item.contains(tool)) {
            return Some(tool);
        }
    }
    None
}

fn table_path(id: &str) -> String {
    format!(
        "data/minecraft/loot_table/{}.json",
        id.strip_prefix("minecraft:").unwrap_or(id)
    )
}

fn normalize(id: &str) -> String {
    id.strip_prefix("minecraft:").unwrap_or(id).to_string()
}

fn write_table(
    out: &mut String,
    record: &str,
    field: &str,
    name: &str,
    drops: &[DropDef],
) {
    out.push_str(&format!(
        "    {record} {{ {field}: {:?}, drops: &[\n",
        name
    ));
    for drop in drops {
        let tool = match &drop.tool {
            Some(tool) => format!("Some({tool:?})"),
            None => "None".to_string(),
        };
        out.push_str(&format!(
            "        Drop {{ item: {:?}, min: {}, max: {}, tool: {} }},\n",
            drop.item, drop.min, drop.max, tool
        ));
    }
    out.push_str("    ] },\n");
}
