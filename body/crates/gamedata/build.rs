fn render_tags(
    item_tags: &BTreeMap<String, BTreeSet<String>>,
    block_tags: &BTreeMap<String, BTreeSet<String>>,
) -> String {
    let mut out = String::from("// Generated by build.rs from the 26.3 server jar. Do not edit.\n\n");
    out.push_str("pub const ITEM_TAGS: &[Tag] = &[\n");
    for (name, values) in item_tags {
        out.push_str(&format!("    Tag {{ name: {:?}, values: &[", name));
        for value in values {
            out.push_str(&format!("{value:?}, "));
        }
        out.push_str("] },\n");
    }
    out.push_str("];\n\npub const BLOCK_TAGS: &[Tag] = &[\n");
    for (name, values) in block_tags {
        out.push_str(&format!("    Tag {{ name: {:?}, values: &[", name));
        for value in values {
            out.push_str(&format!("{value:?}, "));
        }
        out.push_str("] },\n");
    }
    out.push_str("];\n");
    out
}

fn render_recipes(recipes: &[RecipeDef]) -> String {
    let mut out = String::from("// Generated by build.rs from the 26.3 server jar. Do not edit.\n\n");
    out.push_str("pub const RECIPES: &[Recipe] = &[\n");
    for recipe in recipes {
        out.push_str(&format!(
            "    Recipe {{ output: {:?}, output_count: {}, needs_table: {}, shape: ",
            recipe.output, recipe.output_count, recipe.needs_table
        ));
        match &recipe.shape {
            ShapeDef::Shaped {
                width,
                height,
                grid,
            } => {
                out.push_str(&format!(
                    "Shape::Shaped {{ width: {width}, height: {height}, grid: &["
                ));
                for cell in grid {
                    match cell {
                        None => out.push_str("None, "),
                        Some(ingredient) => {
                            out.push_str("Some(");
                            render_ingredient(&mut out, ingredient);
                            out.push_str("), ");
                        }
                    }
                }
                out.push_str("] } },\n");
            }
            ShapeDef::Shapeless { ingredients } => {
                out.push_str("Shape::Shapeless { ingredients: &[");
                for ingredient in ingredients {
                    render_ingredient(&mut out, ingredient);
                    out.push_str(", ");
                }
                out.push_str("] } },\n");
            }
        }
    }
    out.push_str("];\n");
    out
}

fn render_ingredient(out: &mut String, ingredient: &IngredientDef) {
    out.push_str("Ingredient { tag: ");
    match &ingredient.tag {
        Some(tag) => out.push_str(&format!("Some({tag:?})")),
        None => out.push_str("None"),
    }
    out.push_str(", items: &[");
    for item in &ingredient.items {
        out.push_str(&format!("{item:?}, "));
    }
    out.push_str("] }");
}

